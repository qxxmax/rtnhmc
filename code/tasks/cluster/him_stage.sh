#!/bin/bash
B=/lustre/him/him-mam/mqian
LINES=$1 P=$2 EXTRA=$3
J=$SLURM_JOB_ID W=/tmp/mq_$SLURM_JOB_ID
[ -s "$LINES" ] || { echo "no lines file $LINES"; exit 1; }
OUT=$B/himout/$J; mkdir -p $OUT
LOG=$B/logs/stage-$J; mkdir -p $LOG
echo "job $J $SLURM_JOB_NODELIST lines $(wc -l < $LINES) P $P $(date +%T)"
sed "s|/tmp/mq/|$W/|g" $LINES > $LOG/lines.txt
sbcast -f $B/stage/base.tar $W.base.tar || exit 1
sbcast -f $LOG/lines.txt $W.lines.txt || exit 1
sbcast -f $B/revision_code/results_sync/revision/tasks/him_node_run.sh $W.run.sh || exit 1
[ -n "$EXTRA" ] && { sbcast -f $EXTRA $W.extra.tar || exit 1; }
srun -n1 bash -c "mkdir -p $W && tar xf $W.base.tar -C $W && rm $W.base.tar &&
  { [ ! -f $W.extra.tar ] || tar xf $W.extra.tar -C $W; } && mkdir -p $W/revision_runs/longchain_min $W/revision_runs/raw_snis && touch $W/.t0" || exit 1
echo "staged $(date +%T)"
srun -n1 --overlap bash $W.run.sh $W $P ${STOP_S:-41400} &
MAIN=$!
pull() {  # new files under revision_runs (and the line logs) since the last pull
  srun -n1 --overlap bash -c "cd $W; touch .t1; find revision_runs line*.log -newer .t0 -type f ! -path '*/phi4_buffer/*' |
    tar cf - -T -; mv .t1 .t0" | tar xf - -C $OUT && cp -p $OUT/line*.log $LOG/ 2>/dev/null; rm -f $OUT/line*.log
}
while kill -0 $MAIN 2>/dev/null; do
  for k in $(seq 1 90); do kill -0 $MAIN 2>/dev/null || break; sleep 10; done
  pull
done




























































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































wait $MAIN
pull
srun -n1 --overlap rm -rf $W $W.lines.txt $W.extra.tar $W.run.sh
echo "done $(date +%T)"
